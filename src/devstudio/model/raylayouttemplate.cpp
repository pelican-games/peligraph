constexpr std::string_view RecordBegin = "// pelican: shader record";
constexpr std::string_view RecordEnd = "// pelican: end shader record";

std::string jsonText(const nlohmann::json &value, const char *key) {
    const auto found = value.find(key);
    return found != value.end() && found->is_string() ? found->get<std::string>() : std::string{};
}

void replaceAll(std::string &text, std::string_view token, std::string_view value) {
    for (std::size_t at = text.find(token); at != std::string::npos; at = text.find(token, at + value.size()))
        text.replace(at, token.size(), value);
}

std::string glslRecordType(std::string_view type) {
    if (type == "i32") return "int";
    if (type == "u32") return "uint";
    if (type == "f32") return "float";
    return std::string{type};
}

template <typename List> std::size_t indexIn(const List &list, std::string_view name) {
    for (std::size_t index = 0; index < list.size(); ++index)
        if (list[index] == name) return index;
    return 0;
}

bool hasRecordField(const RayLayoutTemplateNames &layout, std::string_view name, std::string_view type) {
    return std::ranges::any_of(layout.record,
                               [&](const auto &field) { return field.first == name && field.second == type; });
}

bool fetchesNormals(const RayLayoutTemplateNames &layout) {
    return std::ranges::find(layout.engine_record, "geometry_index") != layout.engine_record.end();
}

std::string rayLayoutHead(std::string_view name, RayLayoutTemplateStage stage, std::string_view what) {
    return "#version 460\n"
           "#extension GL_GOOGLE_include_directive : enable\n"
           "#extension GL_EXT_ray_tracing : require\n"
           "\n"
           "// " +
           std::string{name} + std::string{rayLayoutTemplateExtension(stage)} + ": " + std::string{what} +
           "\n"
           "\n"
           "// The ray group layout's names (PELICAN_RAY_TYPE_<ray type>, PELICAN_MISS_<miss>,\n"
           "// pelican_ray_type_count), generated by the engine from the layout.\n"
           "#include \"__pelican_ray_group_layout.glsl\"\n";
}

// What recordColor adds for the record's first field.
std::string recordColorTerm(const std::pair<std::string, std::string> &field) {
    const auto member = "record." + field.first;
    if (field.second == "f32") return "vec3(" + member + ")";
    if (field.second == "i32" || field.second == "u32") return "vec3(float(" + member + "))";
    if (field.second == "vec2") return "vec3(" + member + ", 0.0)";
    if (field.second == "vec4") return member + ".rgb";
    return member;
}

// The tint of a group other than the layout's default one, so two groups
// read apart on screen.
std::string groupTint(const RayLayoutTemplateNames &layout, std::string_view group) {
    if (group.empty() || group == layout.default_group) return "vec3(1.0)";
    static constexpr std::array<std::string_view, 4> tints{"vec3(1.0, 0.55, 0.3)", "vec3(0.4, 0.7, 1.0)",
                                                           "vec3(0.55, 1.0, 0.45)", "vec3(1.0, 0.9, 0.35)"};
    std::size_t index = 0;
    for (const auto &[name, type] : layout.groups) {
        if (name == group) break;
        if (name != layout.default_group) ++index;
    }
    return std::string{tints[index % tints.size()]};
}

// The sphere an intersection shader solves for, and a procedural hit's
// normal is taken from: the record's when the layout has center / radius.
std::string sphereLines(const RayLayoutTemplateNames &layout) {
    return std::string{"    vec3 center = "} +
           (hasRecordField(layout, "center", "vec3") ? "record.center" : "vec3(0.0)") +
           ";\n"
           "    float radius = " +
           (hasRecordField(layout, "radius", "f32") ? "record.radius" : "1.0") + ";\n";
}

std::string rayLayoutRaygen(const RayLayoutTemplateNames &layout, const RayLayoutTemplatePlace &place,
                            std::string_view name) {
    const std::string port = "color";
    const auto first_type = layout.ray_types.empty() ? std::string{"primary"} : layout.ray_types.front();
    const auto first_miss = layout.misses.empty() ? std::string{"miss"} : layout.misses.front();
    auto second_type = place.second_ray_type;
    if (second_type.empty() && layout.ray_types.size() > 1) second_type = layout.ray_types[1];
    const bool second = !second_type.empty() && second_type != first_type;
    auto second_miss = place.second_miss;
    if (second_miss.empty()) second_miss = layout.misses.size() > 1 ? layout.misses[1] : first_miss;
    std::string text =
        rayLayoutHead(name, RayLayoutTemplateStage::raygen,
                      "the ray generation shader Studio wrote for a task of a\n"
                      "// project with a ray group layout. One ray of type " +
                          first_type +
                          " per pixel of the image it writes\n"
                          "// (the task's dispatch.rays_from), from the camera through that pixel; the\n"
                          "// colour is what the closest hit of the group it hits gives, or a dim sky\n"
                          "// where it hits nothing (miss " +
                          first_miss + ").") +
        "#include \"pelican_sets.glsl\"\n"
        "#include \"pelican_frame.glsl\"\n"
        "\n";
    if (second)
        text += "// 1: also trace a ray of type " + second_type +
                " from the point hit toward the light, and\n"
                "// darken the point when something is in the way (its closest hit says so; miss\n"
                "// " +
                second_miss + " runs when nothing is).\n";
    else
        text += "// 1: also trace a second ray type (a shadow ray) -- the layout has one ray type\n"
                "// now: add one to it, then name it below.\n";
    text += std::string{"#define TRACE_SECOND_RAY_TYPE "} + (place.trace_second && second ? "1" : "0") +
            "\n"
            "// 1: pass the colour through the task's callable 0 (its first callable shader).\n"
            "#define CALL_CALLABLE_0 " +
            (place.call_callable ? "1" : "0") +
            "\n"
            "\n"
            "// The image the task writes, port \"" +
            port +
            "\".\n"
            "layout(rgba16f, set = PELICAN_SET_PASS_INPUT, binding = 0)\n"
            "    writeonly uniform image2D pelican_resource_" +
            port +
            ";\n"
            "\n"
            "// The scene's acceleration structure (the task's acceleration_structure).\n"
            "layout(set = PELICAN_SET_FRAME, binding = PELICAN_RAY_QUERY_TLAS_BINDING)\n"
            "    uniform accelerationStructureEXT pelicanRayTracingScene;\n"
            "\n"
            "// Payload 0, ray type " +
            first_type +
            "'s: rgb is the colour its closest hit gives, w the\n"
            "// distance to the hit (0: the miss ran, nothing hit).\n"
            "layout(location = 0) rayPayloadEXT vec4 hit;\n"
            "// Payload 1, the second ray type's: 1 when something lies between the point and\n"
            "// the light.\n"
            "layout(location = 1) rayPayloadEXT float occluded;\n"
            "// Callable data 0: the colour handed to a callable shader.\n"
            "layout(location = 0) callableDataEXT vec4 callable_color;\n"
            "\n"
            "const float RAY_MIN_DISTANCE = 0.001;\n"
            "const float RAY_MAX_DISTANCE = 10000.0;\n"
            "const vec3 LIGHT_DIRECTION = normalize(vec3(0.5, 1.0, 0.25));\n"
            "\n"
            "// The direction from the camera through a point of the image, in pixels.\n"
            "vec3 cameraRay(vec2 pixel) {\n"
            "    vec2 ndc = pixel / vec2(gl_LaunchSizeEXT.xy) * 2.0 - 1.0;\n"
            "    vec4 target = inverse(pelicanFrame.projection) * vec4(ndc, 0.5, 1.0);\n"
            "    vec3 direction = normalize(target.xyz / target.w);\n"
            "    return normalize((inverse(pelicanFrame.view) * vec4(direction, 0.0)).xyz);\n"
            "}\n"
            "\n"
            "void main() {\n"
            "    vec2 pixel = vec2(gl_LaunchIDEXT.xy) + vec2(0.5);\n"
            "    vec3 origin = (inverse(pelicanFrame.view) * vec4(0.0, 0.0, 0.0, 1.0)).xyz;\n"
            "    vec3 direction = cameraRay(pixel);\n"
            "    hit = vec4(0.0);\n"
            "    traceRayEXT(pelicanRayTracingScene, gl_RayFlagsOpaqueEXT, 0xff, PELICAN_RAY_TYPE_" +
            first_type +
            ",\n"
            "                pelican_ray_type_count, PELICAN_MISS_" +
            first_miss +
            ", origin, RAY_MIN_DISTANCE, direction,\n"
            "                RAY_MAX_DISTANCE, 0);\n"
            "    vec3 color;\n"
            "    if (hit.w <= 0.0) {\n"
            "        // Nothing hit: a dim sky, lighter upwards.\n"
            "        color = mix(vec3(0.04, 0.05, 0.07), vec3(0.18, 0.26, 0.36),\n"
            "                    clamp(direction.y * 0.5 + 0.5, 0.0, 1.0));\n"
            "    } else {\n"
            "        color = hit.rgb;\n"
            "#if TRACE_SECOND_RAY_TYPE\n";
    if (second)
        text += "        // A ray of type " + second_type +
                " from just above the point toward the light.\n"
                "        vec3 point = origin + direction * (hit.w - 0.001);\n"
                "        occluded = 1.0;\n"
                "        traceRayEXT(pelicanRayTracingScene,\n"
                "                    gl_RayFlagsOpaqueEXT | gl_RayFlagsTerminateOnFirstHitEXT, 0xff,\n"
                "                    PELICAN_RAY_TYPE_" +
                second_type + ", pelican_ray_type_count, PELICAN_MISS_" + second_miss +
                ",\n"
                "                    point, RAY_MIN_DISTANCE, LIGHT_DIRECTION, RAY_MAX_DISTANCE, 1);\n"
                "        if (occluded > 0.5) color *= 0.3;\n";
    else
        text += "        // traceRayEXT(..., PELICAN_RAY_TYPE_<second>, pelican_ray_type_count,\n"
                "        //             PELICAN_MISS_<its miss>, point, ..., LIGHT_DIRECTION, ..., 1);\n";
    text += "#endif\n"
            "    }\n"
            "#if CALL_CALLABLE_0\n"
            "    callable_color = vec4(color, 1.0);\n"
            "    executeCallableEXT(0, 0);\n"
            "    color = callable_color.rgb;\n"
            "#endif\n"
            "    imageStore(pelican_resource_" +
            port +
            ", ivec2(gl_LaunchIDEXT.xy), vec4(color, 1.0));\n"
            "}\n";
    return text;
}

// Payload `index`: ray type 0's is the colour, a later one's whether the
// point is occluded.
std::string payloadIn(std::size_t index) {
    if (index == 0)
        return "// Payload 0, the first ray type's: rgb the colour, w the distance to the hit\n"
               "// (0: nothing hit).\n"
               "layout(location = 0) rayPayloadInEXT vec4 hit;\n";
    return "// Payload " + std::to_string(index) + ", ray type " + std::to_string(index) +
           "'s: 1 when something lies between the point and the light.\n"
           "layout(location = " +
           std::to_string(index) + ") rayPayloadInEXT float occluded;\n";
}

std::string rayLayoutMiss(const RayLayoutTemplateNames &layout, const RayLayoutTemplatePlace &place,
                          std::string_view name) {
    auto index = indexIn(layout.misses, place.miss);
    // Miss i is ray type i's; a miss past the ray types answers the first.
    if (index >= layout.ray_types.size()) index = 0;
    auto text = rayLayoutHead(name, RayLayoutTemplateStage::miss,
                              "the miss shader Studio wrote for miss " +
                                  (place.miss.empty() ? std::string{"0"} : place.miss) +
                                  " of the ray group\n// layout. It runs where a ray that names it "
                                  "hits nothing.") +
                "\n" + payloadIn(index) + "\nvoid main() {\n";
    text += index == 0 ? "    hit = vec4(0.0);\n" : "    occluded = 0.0;\n";
    return text + "}\n";
}

std::string rayLayoutClosestHit(const RayLayoutTemplateNames &layout, const RayLayoutTemplatePlace &place,
                                std::string_view name) {
    const auto type_index = indexIn(layout.ray_types, place.ray_type);
    const auto group = place.group.empty() ? layout.default_group : place.group;
    auto text = rayLayoutHead(name, RayLayoutTemplateStage::closest_hit,
                              "the closest-hit shader Studio wrote for ray type " +
                                  (place.ray_type.empty() ? std::string{"0"} : place.ray_type) +
                                  " and\n// hit group " + group +
                                  " of the ray group layout. It runs at the nearest surface\n"
                                  "// of the group such a ray hits.") +
                "\n" + payloadIn(type_index);
    // RTL-3s, decision 5 (engine EB-3): a hit shader that reads no record
    // declares none -- one that does declares the layout's exactly
    // (pelican.ray_tracing.shader_record_abi_mismatch@1).
    // The hit attribute every hit shader of a procedural group shares with
    // its intersection (pelican.procedural_hit_attribute_mismatch@1): the
    // templates' vec2, in a triangles group the barycentrics.
    if (type_index != 0)
        return text + "hitAttributeEXT vec2 barycentric;\n\nvoid main() {\n    occluded = 1.0;\n}\n";
    const bool normals = fetchesNormals(layout);
    text += "hitAttributeEXT vec2 barycentric;\n\n" + rayRecordBlock(layout) +
            "\n"
            "// The group's tint (the default group's is none).\n"
            "const vec3 GROUP_TINT = " +
            groupTint(layout, group) +
            ";\n"
            "\n"
            "void main() {\n"
            "    vec3 color;\n"
            "    if (gl_HitKindEXT == gl_HitKindFrontFacingTriangleEXT ||\n"
            "        gl_HitKindEXT == gl_HitKindBackFacingTriangleEXT) {\n";
    if (normals)
        text += "        // The triangle's normal, from the engine's geometry table (engine_record's\n"
                "        // geometry_index).\n"
                "        vec3 object_normal = pelicanRayFetchNormal(record.geometry_index, gl_PrimitiveID,\n"
                "                                                   barycentric);\n"
                "        vec3 normal = normalize(transpose(mat3(gl_WorldToObjectEXT)) * object_normal);\n"
                "        color = normal * 0.5 + 0.5;\n";
    else
        text += "        // Where it hit: the normal needs the triangle's vertices, which the engine's\n"
                "        // geometry table serves when the layout's engine_record has geometry_index.\n"
                "        vec3 position = gl_WorldRayOriginEXT + gl_HitTEXT * gl_WorldRayDirectionEXT;\n"
                "        color = fract(position) * 0.75 + 0.25;\n";
    text += "    } else {\n"
            "        // A procedural hit: the normal of the sphere the intersection shader solves\n"
            "        // for, from the point hit in the geometry's own space.\n" +
            sphereLines(layout) +
            "        vec3 local = gl_ObjectRayOriginEXT + gl_HitTEXT * gl_ObjectRayDirectionEXT - center;\n"
            "        vec3 normal = normalize(transpose(mat3(gl_WorldToObjectEXT)) * (local / radius));\n"
            "        color = normal * 0.5 + 0.5;\n"
            "    }\n"
            "    hit = vec4(recordColor(color * GROUP_TINT), gl_HitTEXT);\n"
            "}\n";
    // sphereLines indents by four; inside the else it reads by eight.
    replaceAll(text, "\n    vec3 center = ", "\n        vec3 center = ");
    replaceAll(text, "\n    float radius = ", "\n        float radius = ");
    return text;
}

std::string rayLayoutAnyHit(const RayLayoutTemplateNames &layout, const RayLayoutTemplatePlace &place,
                            std::string_view name) {
    const auto group = place.group.empty() ? layout.default_group : place.group;
    return rayLayoutHead(name, RayLayoutTemplateStage::any_hit,
                         "the any-hit shader Studio wrote for ray type " + place.ray_type +
                             " and hit\n// group " + group +
                             " of the ray group layout. It runs for every surface of the\n"
                             "// group a ray crosses (unless the geometry is opaque) before the "
                             "nearest is\n// chosen.") +
           "\n" +
           // The same payload as the closest hit beside it (the engine checks
           // the pair).
           payloadIn(indexIn(layout.ray_types, place.ray_type)) + "hitAttributeEXT vec2 barycentric;\n\n" +
           // RTL-3s, decision 5: it reads no record, so it declares none.
           "void main() {\n"
           "    // Every candidate is accepted. To let the ray pass through this surface, end\n"
           "    // here with: ignoreIntersectionEXT;\n"
           "}\n";
}

std::string rayLayoutIntersection(const RayLayoutTemplateNames &layout, const RayLayoutTemplatePlace &place,
                                  std::string_view name) {
    const auto group = place.group.empty() ? std::string{"procedural"} : place.group;
    return rayLayoutHead(name, RayLayoutTemplateStage::intersection,
                         "the intersection shader Studio wrote for the procedural\n"
                         "// hit group " +
                             group +
                             " of the ray group layout: a sphere in the procedural geometry's\n"
                             "// own space (the asset's aabb has to hold it), reported where the "
                             "ray enters it.") +
           "\n"
           "hitAttributeEXT vec2 sphere_hit;\n\n" +
           // RTL-3s, decision 5: the record only when the sphere is read
           // from it.
           (hasRecordField(layout, "center", "vec3") || hasRecordField(layout, "radius", "f32")
                ? rayRecordBlock(layout) + "\n"
                : std::string{}) +
           "void main() {\n" +
           sphereLines(layout) +
           "    vec3 origin = gl_ObjectRayOriginEXT - center;\n"
           "    vec3 direction = gl_ObjectRayDirectionEXT;\n"
           "    float a = dot(direction, direction);\n"
           "    float half_b = dot(origin, direction);\n"
           "    float c = dot(origin, origin) - radius * radius;\n"
           "    float discriminant = half_b * half_b - a * c;\n"
           "    if (discriminant < 0.0) return;\n"
           "    float root = sqrt(discriminant);\n"
           "    float t = (-half_b - root) / a;\n"
           "    if (t < gl_RayTminEXT || t > gl_RayTmaxEXT) {\n"
           "        // A ray that starts inside leaves through the farther root.\n"
           "        t = (-half_b + root) / a;\n"
           "        if (t < gl_RayTminEXT || t > gl_RayTmaxEXT) return;\n"
           "    }\n"
           "    sphere_hit = vec2(t, 0.0);\n"
           "    reportIntersectionEXT(t, 0u);\n"
           "}\n";
}

std::string rayLayoutCallable(std::string_view name) {
    return rayLayoutHead(name, RayLayoutTemplateStage::callable,
                         "the callable shader Studio wrote for a task of a project\n"
                         "// with a ray group layout. A shader of the task calls it by its index in "
                         "the task's\n// callable list (executeCallableEXT(<index>, 0)).") +
           "\n"
           "// Callable data 0: the colour it is handed, and gives back.\n"
           "layout(location = 0) callableDataInEXT vec4 callable_color;\n"
           "\n"
           "void main() {\n"
           "    // A warm tint.\n"
           "    callable_color.rgb = callable_color.rgb * vec3(1.0, 0.5, 0.25) + vec3(0.25, 0.05, 0.0);\n"
           "}\n";
}

// The line `#define <name> <value>`: where its value is, or npos.
std::size_t switchValueAt(std::string_view source, std::string_view name) {
    const auto token = "#define " + std::string{name} + " ";
    for (auto at = source.find(token); at != std::string_view::npos; at = source.find(token, at + 1)) {
        if (at != 0 && source[at - 1] != '\n') continue;
        const auto value = at + token.size();
        if (value < source.size() && (source[value] == '0' || source[value] == '1')) return value;
    }
    return std::string_view::npos;
}

