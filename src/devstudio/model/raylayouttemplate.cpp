std::optional<RayLayoutTemplateNames> rayLayoutTemplateNamesFromDocument(const nlohmann::json &document) {
    if (!document.is_object()) return std::nullopt;
    RayLayoutTemplateNames names;
    for (const auto &type : document.value("ray_types", nlohmann::json::array()))
        if (type.is_string()) names.ray_types.push_back(type.get<std::string>());
    if (names.ray_types.empty()) return std::nullopt;
    for (const auto &miss : document.value("misses", nlohmann::json::array())) {
        if (miss.is_string()) names.misses.push_back(miss.get<std::string>());
        else if (miss.is_object() && !jsonText(miss, "name").empty()) names.misses.push_back(jsonText(miss, "name"));
    }
    for (const auto &group : document.value("groups", nlohmann::json::array()))
        if (group.is_object() && !jsonText(group, "name").empty())
            names.groups.emplace_back(jsonText(group, "name"), jsonText(group, "type"));
    names.default_group = jsonText(document, "default_group");
    for (const auto &field : document.value("engine_record", nlohmann::json::array()))
        if (field.is_string()) names.engine_record.push_back(field.get<std::string>());
    for (const auto &field : document.value("record", nlohmann::json::array()))
        if (field.is_object() && !jsonText(field, "name").empty())
            names.record.emplace_back(jsonText(field, "name"), jsonText(field, "type"));
    return names;
}

std::string_view rayLayoutTemplateExtension(RayLayoutTemplateStage stage) {
    switch (stage) {
    case RayLayoutTemplateStage::raygen: return ".rgen";
    case RayLayoutTemplateStage::miss: return ".rmiss";
    case RayLayoutTemplateStage::closest_hit: return ".rchit";
    case RayLayoutTemplateStage::any_hit: return ".rahit";
    case RayLayoutTemplateStage::intersection: return ".rint";
    case RayLayoutTemplateStage::callable: return ".rcall";
    }
    return ".rgen";
}

std::string rayLayoutShaderTemplate(const RayLayoutTemplateNames &layout, const RayLayoutTemplatePlace &place,
                                    std::string_view name) {
    switch (place.stage) {
    case RayLayoutTemplateStage::raygen: return rayLayoutRaygen(layout, place, name);
    case RayLayoutTemplateStage::miss: return rayLayoutMiss(layout, place, name);
    case RayLayoutTemplateStage::closest_hit: return rayLayoutClosestHit(layout, place, name);
    case RayLayoutTemplateStage::any_hit: return rayLayoutAnyHit(layout, place, name);
    case RayLayoutTemplateStage::intersection: return rayLayoutIntersection(layout, place, name);
    case RayLayoutTemplateStage::callable: return rayLayoutCallable(name);
    }
    return {};
}

std::optional<bool> rayLayoutRaygenSwitch(std::string_view source, std::string_view name) {
    const auto at = switchValueAt(source, name);
    if (at == std::string_view::npos) return std::nullopt;
    return source[at] == '1';
}

std::optional<std::string> setRayLayoutRaygenSwitch(std::string_view source, std::string_view name, bool on) {
    const auto at = switchValueAt(source, name);
    if (at == std::string_view::npos) return std::nullopt;
    std::string text{source};
    text[at] = on ? '1' : '0';
    return text;
}

std::string rayRecordBlock(const RayLayoutTemplateNames &layout) {
    std::string block = std::string{RecordBegin} +
                        ": Studio writes this block again when the ray group layout's\n"
                        "// record changes. The engine's fields (engine_record), then the layout's own\n"
                        "// (record), in order -- every hit shader of a traced ray type declares them.\n";
    if (!layout.engine_record.empty() || !layout.record.empty()) {
        block += "layout(shaderRecordEXT, std430) buffer PelicanHitRecord {\n";
        if (!layout.engine_record.empty()) block += "    PELICAN_RAY_ENGINE_RECORD_MEMBERS\n";
        for (const auto &[field, type] : layout.record) block += "    " + glslRecordType(type) + " " + field + ";\n";
        block += "} record;\n";
    }
    if (layout.record.empty())
        block += "// The colour a closest hit gives, as it is (the layout has no record field).\n"
                 "vec3 recordColor(vec3 color) { return color; }\n";
    else
        block += "// The record's first field (" + layout.record.front().first +
                 "), added to the colour a closest hit gives.\n"
                 "vec3 recordColor(vec3 color) { return color + " +
                 recordColorTerm(layout.record.front()) + "; }\n";
    return block + std::string{RecordEnd} + "\n";
}

bool hasRayRecordBlock(std::string_view source) {
    const auto begin = source.find(RecordBegin);
    return begin != std::string_view::npos && source.find(RecordEnd, begin) != std::string_view::npos;
}

bool declaresRayShaderRecord(std::string_view source) {
    return source.find("shaderRecordEXT") != std::string_view::npos;
}

std::optional<std::string> rewriteRayRecordBlock(std::string_view source, const RayLayoutTemplateNames &layout) {
    auto begin = source.find(RecordBegin);
    if (begin == std::string_view::npos) return std::nullopt;
    const auto end_marker = source.find(RecordEnd, begin);
    if (end_marker == std::string_view::npos) return std::nullopt;
    begin = source.rfind('\n', begin);
    begin = begin == std::string_view::npos ? 0 : begin + 1;
    auto end = source.find('\n', end_marker);
    end = end == std::string_view::npos ? source.size() : end + 1;
    const bool crlf = source.find("\r\n") != std::string_view::npos;
    auto block = rayRecordBlock(layout);
    if (crlf) replaceAll(block, "\n", "\r\n");
    return std::string{source.substr(0, begin)} + block + std::string{source.substr(end)};
}

